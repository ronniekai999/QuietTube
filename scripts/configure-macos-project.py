#!/usr/bin/env python3
"""Configure Apple's generated Safari project with QuietTube's native Mac code."""
import argparse
import hashlib
import json
import plistlib
import shutil
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('generated_project', type=Path)
parser.add_argument('--team', required=True)
options = parser.parse_args()
project = Path(__file__).resolve().parent.parent
generated = options.generated_project.resolve()
pbx = generated / 'QuietTube.xcodeproj/project.pbxproj'
data = json.loads(subprocess.check_output(['plutil', '-convert', 'json', '-o', '-', str(pbx)]))
objects = data['objects']
version = (project / 'mac/VERSION').read_text().strip()
extension_id = (project / 'extension-id.txt').read_text().strip()
group = options.team + '.com.quiettube.shared'
configuration = generated / 'BuildConfiguration.swift'
configuration.write_text('// Generated by configure-macos-project.py.\n'
    'enum BuildConfiguration {\n'
    f'    static let appGroup = {json.dumps(group)}\n'
    f'    static let version = {json.dumps(version)}\n'
    f'    static let chromeExtensionId = {json.dumps(extension_id)}\n'
    '    static let safariExtensionId = "com.quiettube.mac.SafariExtension"\n}\n')

def identifier(value):
    return hashlib.sha256(('QuietTube:' + value).encode()).hexdigest()[:24].upper()

def reference(path, kind):
    key = identifier(str(path))
    objects[key] = {'isa': 'PBXFileReference', 'lastKnownFileType': kind,
                    'name': path.name, 'path': str(path), 'sourceTree': '<absolute>'}
    return key

def add_to_phase(phase, path, kind):
    ref = reference(path, kind)
    key = identifier(phase + str(path))
    objects[key] = {'isa': 'PBXBuildFile', 'fileRef': ref}
    objects[phase]['files'].append(key)

shared = list(sorted((project / 'mac/Shared').glob('*.swift'))) + [configuration]
targets = [item for item in objects.values() if item['isa'] == 'PBXNativeTarget']
for target in targets:
    extension = target['productType'] == 'com.apple.product-type.app-extension'
    phases = {objects[key]['isa']: key for key in target['buildPhases']}
    source_phase = phases['PBXSourcesBuildPhase']
    objects[source_phase]['files'] = []
    sources = shared + (list(sorted((project / 'mac/SafariExtension').glob('*.swift'))) if extension
                        else list(sorted((project / 'mac/App').glob('*.swift'))))
    for source in sources:
        add_to_phase(source_phase, source, 'sourcecode.swift')
    if not extension:
        resource_phase = phases['PBXResourcesBuildPhase']
        objects[resource_phase]['files'] = []
        add_to_phase(resource_phase, generated / 'QuietTube/Assets.xcassets', 'folder.assetcatalog')
        add_to_phase(resource_phase, generated.parent.parent / 'build/ChromeExtension', 'folder')
    bundle_id = 'com.quiettube.mac.SafariExtension' if extension else 'com.quiettube.mac'
    folder = generated / ('QuietTube Extension' if extension else 'QuietTube')
    entitlements = {'com.apple.security.application-groups': [group]}
    if extension:
        entitlements['com.apple.security.app-sandbox'] = True
    (folder / 'QuietTube.entitlements').write_bytes(plistlib.dumps(entitlements))
    info = {'CFBundleDevelopmentRegion': 'en', 'CFBundleDisplayName': 'QuietTube',
            'CFBundleExecutable': '$(EXECUTABLE_NAME)', 'CFBundleIdentifier': '$(PRODUCT_BUNDLE_IDENTIFIER)',
            'CFBundleInfoDictionaryVersion': '6.0', 'CFBundleName': 'QuietTube',
            'CFBundlePackageType': 'XPC!' if extension else 'APPL', 'CFBundleShortVersionString': version,
            'CFBundleVersion': '1', 'LSMinimumSystemVersion': '14.0',
            'NSHumanReadableCopyright': 'QuietTube contributors. GPL-3.0-or-later.'}
    if extension:
        info['NSExtension'] = {'NSExtensionPointIdentifier': 'com.apple.Safari.web-extension',
                              'NSExtensionPrincipalClass': '$(PRODUCT_MODULE_NAME).SafariWebExtensionHandler'}
    else:
        info.update(LSUIElement=True, NSPrincipalClass='NSApplication', NSHighResolutionCapable=True)
    (folder / 'Info.plist').write_bytes(plistlib.dumps(info))
    config_list = objects[target['buildConfigurationList']]
    for key in config_list['buildConfigurations']:
        settings = objects[key]['buildSettings']
        # Explicit targets avoid new Xcode template defaults that would isolate
        # shared file/protocol code to the main actor or load a sample storyboard.
        for name in list(settings):
            if name.startswith('INFOPLIST_KEY_') or name.startswith('SWIFT_UPCOMING_FEATURE_'):
                del settings[name]
        settings.update(PRODUCT_BUNDLE_IDENTIFIER=bundle_id, CODE_SIGN_STYLE='Manual',
            DEVELOPMENT_TEAM=options.team, CODE_SIGN_ENTITLEMENTS=str(folder / 'QuietTube.entitlements'),
            CODE_SIGN_INJECT_BASE_ENTITLEMENTS='NO', GENERATE_INFOPLIST_FILE='NO',
            INFOPLIST_FILE=str(folder / 'Info.plist'), MARKETING_VERSION=version, CURRENT_PROJECT_VERSION='1',
            MACOSX_DEPLOYMENT_TARGET='14.0', SWIFT_VERSION='5.0', SWIFT_DEFAULT_ACTOR_ISOLATION='nonisolated',
            SWIFT_APPROACHABLE_CONCURRENCY='NO', REGISTER_APP_GROUPS='NO',
            ENABLE_APP_SANDBOX='YES' if extension else 'NO', ENABLE_USER_SELECTED_FILES='NO',
            ENABLE_OUTGOING_NETWORK_CONNECTIONS='NO', ENABLE_HARDENED_RUNTIME='YES')
pbx.write_bytes(plistlib.dumps(data, sort_keys=False))

# Generate standard Mac icon entries using the existing QuietTube mark.
icons = generated / 'QuietTube/Assets.xcassets/AppIcon.appiconset'
icons.mkdir(parents=True, exist_ok=True)
for old_icon in icons.glob('*.png'):
    old_icon.unlink()
entries = []
for points in [16, 32, 128, 256, 512]:
    for scale in [1, 2]:
        pixels = points * scale
        filename = f'quiettube-{points}@{scale}x.png'
        subprocess.run(['sips', '-z', str(pixels), str(pixels), str(project / 'assets/quiettube.png'),
                        '--out', str(icons / filename)], check=True, capture_output=True)
        entries.append({'idiom': 'mac', 'size': f'{points}x{points}', 'scale': f'{scale}x', 'filename': filename})
(icons / 'Contents.json').write_text(json.dumps({'images': entries, 'info': {'version': 1, 'author': 'QuietTube'}}, indent=2) + '\n')
(generated / 'Host.entitlements').write_bytes(plistlib.dumps({'com.apple.security.application-groups': [group]}))
print(json.dumps({'project': str(pbx.parent), 'appGroup': group, 'version': version}))
